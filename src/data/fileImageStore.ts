import { Directory, File, Paths } from 'expo-file-system';

import { generateId } from '../core/id';
import type { AssetImageStore, PickedImage } from '../domain/media';

const VALID_REF = /^[a-z0-9-]+\.jpg$/;

/**
 * Mobile photo store: JPEG files in the app's private documents folder
 * (`<documents>/asset_images/`). The database keeps only the file name, so
 * the folder can move between app updates without breaking references.
 */
export class FileImageStore implements AssetImageStore {
  private readonly directory = new Directory(Paths.document, 'asset_images');

  private file(reference: string) {
    // References are generated by save(); reject anything that could escape.
    if (!VALID_REF.test(reference)) throw new Error(`Not a photo reference: ${reference}`);
    return new File(this.directory, reference);
  }

  async save(image: PickedImage) {
    this.directory.create({ idempotent: true, intermediates: true });
    const ref = `${generateId()}.jpg`;
    await new File(image.uri).copy(this.file(ref), { overwrite: true });
    return ref;
  }

  async resolve(reference: string) {
    const file = this.file(reference);
    return file.exists ? file.uri : null;
  }

  async delete(reference: string) {
    const file = this.file(reference);
    if (file.exists) file.delete();
  }

  async references() {
    if (!this.directory.exists) return new Set<string>();
    return new Set(
      this.directory
        .list()
        .map((entry) => entry.name)
        .filter((name) => VALID_REF.test(name)),
    );
  }
}
